<?php
declare(strict_types=1);

function ssg_db(): PDO
{
    static $connection = null;

    if ($connection instanceof PDO) {
        return $connection;
    }

    $databaseUrl = getenv('POSTGRES_URL_NON_POOLING')
        ?: getenv('POSTGRES_URL')
        ?: getenv('DATABASE_URL')
        ?: getenv('POSTGRES_PRISMA_URL')
        ?: '';

    if ($databaseUrl !== '') {
        $parts = parse_url($databaseUrl);
        if (!is_array($parts) || !in_array($parts['scheme'] ?? '', ['postgres', 'postgresql'], true)) {
            throw new RuntimeException('The PostgreSQL connection URL is invalid.');
        }

        $host = $parts['host'] ?? '';
        $port = $parts['port'] ?? 5432;
        $name = rawurldecode(ltrim($parts['path'] ?? '', '/'));
        $user = rawurldecode($parts['user'] ?? '');
        $password = rawurldecode($parts['pass'] ?? '');
        parse_str($parts['query'] ?? '', $options);
        $sslMode = $options['sslmode'] ?? 'require';
    } else {
        $host = getenv('PGHOST') ?: getenv('DB_HOST') ?: '127.0.0.1';
        $port = (int) (getenv('PGPORT') ?: getenv('DB_PORT') ?: '5432');
        $name = getenv('PGDATABASE') ?: getenv('DB_NAME') ?: 'ssg_voting';
        $user = getenv('PGUSER') ?: getenv('DB_USER') ?: 'postgres';
        $password = getenv('PGPASSWORD') ?: getenv('DB_PASSWORD') ?: '';
        $sslMode = getenv('PGSSLMODE') ?: 'prefer';
    }

    if (!is_string($host) || $host === '' || !is_string($name) || $name === ''
        || !is_string($user) || $user === '' || !is_numeric($port)
        || !in_array($sslMode, ['disable', 'allow', 'prefer', 'require', 'verify-ca', 'verify-full'], true)) {
        throw new RuntimeException('The PostgreSQL connection settings are incomplete or invalid.');
    }

    $dsn = sprintf(
        'pgsql:host=%s;port=%d;dbname=%s;sslmode=%s',
        $host,
        (int) $port,
        $name,
        $sslMode
    );

    $connection = new PDO($dsn, $user, $password, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]);

    $schema = [
        "CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username VARCHAR(32) NOT NULL UNIQUE,
            display_name VARCHAR(100) NOT NULL,
            password_hash VARCHAR(255) NOT NULL,
            role VARCHAR(7) NOT NULL CHECK (role IN ('admin', 'student')),
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )",

        "CREATE TABLE IF NOT EXISTS positions (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name VARCHAR(80) NOT NULL UNIQUE,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )",

        "CREATE TABLE IF NOT EXISTS candidates (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            position_id INTEGER NOT NULL,
            name VARCHAR(100) NOT NULL,
            statement TEXT NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT fk_candidates_position
                FOREIGN KEY (position_id) REFERENCES positions(id)
        )",

        "CREATE TABLE IF NOT EXISTS voter_participation (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            voter_id INTEGER NOT NULL UNIQUE,
            submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT fk_participation_voter
                FOREIGN KEY (voter_id) REFERENCES users(id)
        )",

        "CREATE TABLE IF NOT EXISTS ballots (
            position_id INTEGER NOT NULL,
            candidate_id INTEGER NOT NULL,
            CONSTRAINT fk_ballots_position
                FOREIGN KEY (position_id) REFERENCES positions(id),
            CONSTRAINT fk_ballots_candidate
                FOREIGN KEY (candidate_id) REFERENCES candidates(id)
        )",

        "CREATE TABLE IF NOT EXISTS election_settings (
            id SMALLINT PRIMARY KEY,
            is_open SMALLINT NOT NULL DEFAULT 0 CHECK (is_open IN (0, 1)),
            results_published SMALLINT NOT NULL DEFAULT 0 CHECK (results_published IN (0, 1)),
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )",

        "CREATE TABLE IF NOT EXISTS app_sessions (
            id VARCHAR(128) PRIMARY KEY,
            data TEXT NOT NULL,
            expires_at TIMESTAMP NOT NULL
        )",

        'CREATE INDEX IF NOT EXISTS ballots_position_idx ON ballots(position_id)',
        'CREATE INDEX IF NOT EXISTS ballots_candidate_idx ON ballots(candidate_id)',
        'CREATE INDEX IF NOT EXISTS app_sessions_expires_at_idx ON app_sessions(expires_at)',
    ];

    foreach ($schema as $statement) {
        $connection->exec($statement);
    }

    $connection->exec(
        'INSERT INTO election_settings (id, is_open, results_published)
        VALUES (1, 0, 0)
        ON CONFLICT (id) DO NOTHING'
    );

    return $connection;
}

function ssg_execute(PDO $db, string $sql, array $parameters = []): PDOStatement
{
    $statement = $db->prepare($sql);
    $statement->execute($parameters);
    return $statement;
}

function ssg_one(PDO $db, string $sql, array $parameters = []): ?array
{
    $row = ssg_execute($db, $sql, $parameters)->fetch();
    return $row === false ? null : $row;
}

function ssg_all(PDO $db, string $sql, array $parameters = []): array
{
    return ssg_execute($db, $sql, $parameters)->fetchAll();
}

final class SsgPostgresSessionHandler implements SessionHandlerInterface, SessionUpdateTimestampHandlerInterface
{
    private ?string $lockedSessionId = null;

    public function __construct(private PDO $db)
    {
    }

    public function open(string $path, string $name): bool
    {
        return true;
    }

    public function close(): bool
    {
        if ($this->lockedSessionId === null) {
            return true;
        }

        try {
            ssg_execute(
                $this->db,
                'SELECT pg_advisory_unlock(hashtextextended(?, 0))',
                [$this->lockedSessionId]
            );
            $this->lockedSessionId = null;
            return true;
        } catch (PDOException $exception) {
            error_log('SSG Voting session lock release failed: ' . $exception->getMessage());
            return false;
        }
    }

    public function read(string $id): string|false
    {
        ssg_execute($this->db, 'SELECT pg_advisory_lock(hashtextextended(?, 0))', [$id]);
        $this->lockedSessionId = $id;

        $row = ssg_one(
            $this->db,
            'SELECT data FROM app_sessions WHERE id = ? AND expires_at > CURRENT_TIMESTAMP',
            [$id]
        );

        return $row ? (string) $row['data'] : '';
    }

    public function write(string $id, string $data): bool
    {
        ssg_execute(
            $this->db,
            "INSERT INTO app_sessions (id, data, expires_at)
            VALUES (?, ?, CURRENT_TIMESTAMP + CAST(? AS INTEGER) * INTERVAL '1 second')
            ON CONFLICT (id) DO UPDATE
            SET data = EXCLUDED.data, expires_at = EXCLUDED.expires_at",
            [$id, $data, (int) ini_get('session.gc_maxlifetime')]
        );

        return true;
    }

    public function destroy(string $id): bool
    {
        ssg_execute($this->db, 'DELETE FROM app_sessions WHERE id = ?', [$id]);
        return true;
    }

    public function gc(int $max_lifetime): int|false
    {
        return ssg_execute(
            $this->db,
            'DELETE FROM app_sessions WHERE expires_at <= CURRENT_TIMESTAMP'
        )->rowCount();
    }

    public function validateId(string $id): bool
    {
        return ssg_one(
            $this->db,
            'SELECT id FROM app_sessions WHERE id = ? AND expires_at > CURRENT_TIMESTAMP',
            [$id]
        ) !== null;
    }

    public function updateTimestamp(string $id, string $data): bool
    {
        $statement = ssg_execute(
            $this->db,
            "UPDATE app_sessions
            SET expires_at = CURRENT_TIMESTAMP + CAST(? AS INTEGER) * INTERVAL '1 second'
            WHERE id = ?",
            [(int) ini_get('session.gc_maxlifetime'), $id]
        );

        return $statement->rowCount() > 0 || $this->write($id, $data);
    }
}
